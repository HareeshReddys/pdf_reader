const assert = require('node:assert/strict');
const { RealtimeQuestionBuffer } = require('../dist/shared/realtimeQuestionBuffer');
const { isInterviewRequest } = require('../dist/shared/realtimeTurnFilter');
for (const text of ['Why?', 'Complexity?', 'Time complexity', 'Space complexity?', 'Show code', 'Example?', 'Continue', 'Redis?', 'What is a closure?', 'And what happens on failure?']) assert.equal(isInterviewRequest(text, true), true, text);
for (const text of ['Hmm', 'Yeah okay', 'Skenkalne', 'Get article', 'Excuse me.', "That's it."]) assert.equal(isInterviewRequest(text, true), false, text);
assert.equal(isInterviewRequest('What is a closure?', true, [{logprob: -3}]), false);
const buffer = new RealtimeQuestionBuffer();
buffer.add('one', 'How do you cache API responses?', 0);
assert.deepEqual(buffer.take(), {id: 'one', question: 'How do you cache API responses?', combined: false}, 'Dispatch immediately');
buffer.add('two', 'How do you invalidate them?', 1000);
buffer.answerCompleted(2000);
assert.deepEqual(buffer.take(), {id: 'two', question: 'How do you cache API responses? How do you invalidate them?', combined: true});
buffer.answerCompleted(10000);
buffer.add('three', 'Complexity?', 13000);
assert.equal(buffer.take().combined, true, 'Exactly three seconds is a continuation');
buffer.answerCompleted(20000);
buffer.add('four', 'Why?', 23001);
assert.deepEqual(buffer.take(), {id: 'four', question: 'Why?', combined: false});
buffer.answerCompleted(30000);
buffer.add('five', 'How do you handle failures?', 31000);
buffer.add('six', 'And verify recovery?', 32000);
assert.equal(buffer.take().question, 'Why? How do you handle failures? And verify recovery?');
buffer.reset();
buffer.add('fresh', 'Explain React.', 33000);
assert.equal(buffer.take().combined, false);
assert.equal(buffer.take(), undefined);
buffer.imageContext();
buffer.answerCompleted(40000);
buffer.add('image-followup', 'How many rows?', 42000);
assert.equal(buffer.take().question, 'Analyze the submitted screenshot How many rows?', 'Image follow-ups must not combine an unrelated prior spoken question');
console.log('PASS: immediate dispatch, in-flight continuation, 3-second completion boundary, grouped revisions, session reset, and noise/short-follow-up gate.');
