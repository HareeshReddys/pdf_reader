const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { app, BrowserWindow, ipcMain, nativeImage } = require('electron');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'continuous-voice-test-'));
  process.env.INTERVIEW_COPILOT_DATA_DIR = directory;
  require('dotenv').config = () => ({ parsed: {} });
  const originalFetch = global.fetch;
  let window;
  let service;
  let overlayWindow;
  let exitCode = 0;
  try {
    const { RealtimeTranscript } = require('../dist/shared/realtimeTranscript');
    const parser = new RealtimeTranscript();
    const { isAcknowledgmentOnly } = require('../dist/shared/realtimeTurnFilter');
    for (const text of ['Hmm', 'Mm-hmm.', 'Yeah, okay', 'Right', 'Thanks', 'Good. Good.', 'Uhum.', 'Nice.', 'Whom', 'Uh-huh', 'Perfect, exactly', 'Sounds good', 'All right']) assert.equal(isAcknowledgmentOnly(text), true, text);
    for (const text of ['Okay, explain closures', 'Why?', 'Continue', 'Yes, show an example', 'What about that screenshot?', 'Good, explain transactions', 'To whom should the service send events?', 'What makes a good API?', 'Explain HTTP 200', 'नमस्ते']) assert.equal(isAcknowledgmentOnly(text), false, text);
    parser.accept({ type: 'input_audio_buffer.speech_started', item_id: 'input1' });
    parser.accept({ type: 'response.created', response: { id: 'response1' } });
    assert.equal(parser.accept({ type: 'response.output_audio_transcript.delta', response_id: 'response1', delta: 'Answer' }).question, 'Spoken turn (transcription pending)');
    assert.equal(parser.accept({ type: 'response.done', response: { id: 'response1', status: 'completed' } }).complete, false);
    const final = parser.accept({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'input1', transcript: 'Question one?' });
    assert.equal(final.question, 'Question one?'); assert.equal(final.complete, true); assert.equal(final.answer, 'Answer');
    parser.accept({ type: 'input_audio_buffer.speech_started', item_id: 'input2' });
    assert.equal(parser.accept({ type: 'response.output_audio_transcript.delta', response_id: 'response1', delta: ' late' }), undefined);
    parser.accept({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'input2', transcript: 'Question two?' });
    parser.accept({ type: 'response.created', response: { id: 'response2' } });
    assert.equal(parser.accept({ type: 'response.done', response: { id: 'response2', status: 'cancelled', output: [{ content: [{ transcript: 'Partial' }] }] } }).interrupted, true);
    assert.equal(parser.accept({ type: 'rate_limits.updated' }), undefined);
    const screen = require('../dist/main/services/screenCaptureService');
    const contextService = require('../dist/main/services/realtimeContextService');
    process.env.INTERVIEW_COPILOT_REFERENCE_DIR = path.join(directory, 'reference');
    await fs.mkdir(path.join(directory, 'notes'), { recursive: true });
    await fs.writeFile(path.join(directory, 'notes', 'resume.md'), 'Candidate works at Example Labs on PostgreSQL billing APIs. No production incident is documented.');
    await fs.writeFile(path.join(directory, 'notes', 'generic-interview.md'), 'Another candidate built a rocket. This is not candidate experience.');
    await require('../dist/main/services/jobDescriptionService').saveJobDescription('Target role requires Kubernetes. This is a requirement, not past candidate experience.');
    const snapshot = await contextService.buildRealtimeContext();
    assert.deepEqual(snapshot.sourceNames, ['resume.md']);
    assert.equal(snapshot.hasJobDescription, true);
    assert.ok(snapshot.instructions.includes('Example Labs'));
    assert.ok(snapshot.instructions.includes('Hypothetical practice scenario'));
    assert.ok(snapshot.instructions.includes('JD describes the target role'));
    assert.ok(!snapshot.instructions.includes('built a rocket'));
    screen.listScreenCaptureSources = async () => [{ id: 'window:test', name: 'Test image' }];
    screen.captureScreenAndExtractText = async () => ({ imageDataUrl: nativeImage.createFromBitmap(Buffer.from([255, 255, 255, 255]), { width: 1, height: 1 }).toDataURL() });
    service = require('../dist/main/services/realtimeVoiceService');
    delete process.env.OPENAI_API_KEY;
    await assert.rejects(service.connectRealtimeVoice(123, 'v=0\r\n'), /missing/);
    await assert.rejects(service.connectRealtimeVoice(123, 'bad'), /Invalid/);
    process.env.OPENAI_API_KEY = 'test-key-never-exposed';
    global.fetch = async (url, request) => {
      assert.equal(url, 'https://api.openai.com/v1/realtime/calls');
      assert.equal(request.headers.Authorization, 'Bearer test-key-never-exposed');
      const session = JSON.parse(request.body.get('session'));
      assert.equal(session.audio.input.turn_detection.type, 'semantic_vad');
      assert.deepEqual(session.output_modalities, ['text']);
      assert.ok(session.instructions.includes('Example Labs'));
      assert.ok(session.instructions.includes('Target role requires Kubernetes'));
      return new Response('v=0\r\ns=mock-answer\r\n');
    };
    window = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { preload: path.resolve(__dirname, '../dist/main/preload.js'), contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } });
    require('../dist/main/ipc').registerIpcHandlers(() => window);
    ipcMain.removeHandler('runtime:status'); ipcMain.handle('runtime:status', () => ({ openAIConfigured: true, codexEnabled: false }));
    await window.loadFile(path.resolve(__dirname, '../dist/renderer/index.html'));
    await window.webContents.executeJavaScript(`
      window.__voiceTracks = []; window.__voiceMessages = [];
      navigator.mediaDevices.getUserMedia = async () => {
        const track = { enabled: true, stopped: false, stop() { this.stopped = true; } };
        window.__voiceTracks.push(track);
        return { getTracks: () => [track], getAudioTracks: () => [track] };
      };
      navigator.mediaDevices.enumerateDevices = async () => [{ kind: 'audioinput', deviceId: 'test-input', label: 'Voicemeeter Out B1 (Test input)' }];
      window.RTCPeerConnection = class {
        connectionState = 'new'; sctp = { maxMessageSize: 65536 };
        addTrack() {}
        createDataChannel() { const channel = { readyState: 'connecting', bufferedAmount: 0, send(value) { window.__voiceMessages.push(JSON.parse(value)); }, close() { this.readyState = 'closed'; } }; window.__voiceChannel = channel; return channel; }
        async createOffer() { return { sdp: 'v=0\\r\\ns=mock-offer\\r\\n' }; }
        async setLocalDescription() {}
        async setRemoteDescription() { this.connectionState = 'connected'; window.__voiceChannel.readyState = 'open'; window.__voiceChannel.onopen(); this.onconnectionstatechange(); }
        close() { this.connectionState = 'closed'; }
      };
      void 0;
    `);
    const click = text => window.webContents.executeJavaScript(`Array.from(document.querySelectorAll('button')).find(button => button.textContent === ${JSON.stringify(text)}).click()`);
    await click('Start continuous voice');
    for (let i = 0; i < 100 && !(await window.webContents.executeJavaScript("document.querySelector('[aria-label=\"Continuous API voice\"]').textContent.includes('Listening')")); i++) await wait(20);
    assert.equal(service.isRealtimeVoiceActive(), true);
    const promptSnapshot = await window.webContents.executeJavaScript('window.interviewAPI.getRealtimeContextSummary()');
    assert.deepEqual(promptSnapshot.sourceNames, ['resume.md']);
    const emit = event => window.webContents.executeJavaScript(`window.__voiceChannel.onmessage({ data: ${JSON.stringify(JSON.stringify(event))} })`);
    await emit({ type: 'input_audio_buffer.speech_started', item_id: 'turn1' });
    await emit({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'turn1', transcript: 'What is a closure?' });
    assert.equal(await window.webContents.executeJavaScript("window.__voiceMessages.filter(m => m.type === 'response.create').length"), 1, 'The transcript must request an answer immediately without a settle timer');
    await emit({ type: 'response.created', response: { id: 'reply1' } });
    const closureAnswer = ('A function retaining its lexical scope.\n\n').repeat(50);
    await emit({ type: 'response.output_audio_transcript.delta', response_id: 'reply1', delta: closureAnswer });
    await wait(100);
    const overlay = require('../dist/main/services/overlayService');
    overlayWindow = overlay.createOverlayWindow();
    if (overlayWindow.webContents.isLoading()) await new Promise(resolve => overlayWindow.webContents.once('did-finish-load', resolve));
    const clickThroughToggle = () => overlayWindow.webContents.executeJavaScript("document.querySelector('[aria-label=\"Toggle click-through\"]').click()");
    await clickThroughToggle(); await wait(50);
    assert.equal(overlay.getOverlayState().clickThrough, true);
    await clickThroughToggle(); await wait(50);
    assert.equal(overlay.getOverlayState().clickThrough, false);
    assert.equal(await overlayWindow.webContents.executeJavaScript("getComputedStyle(document.querySelector('[aria-label=\"Resize overlay\"]')).cursor"), 'default');
    const originalBounds = overlayWindow.getBounds();
    await overlayWindow.webContents.executeJavaScript(`window.interviewAPI.resizeOverlay(${originalBounds.width + 30}, ${originalBounds.height + 30})`);
    assert.ok(overlayWindow.getBounds().width > originalBounds.width, 'Overlay must remain resizable with the normal cursor');
    overlayWindow.setBounds(originalBounds);
    assert.equal(overlay.getOverlayState().streamingAnswer, closureAnswer);
    const beforeFillers = await window.webContents.executeJavaScript('window.__voiceMessages.length');
    for (const [index, transcript] of ['Hmm', 'Yeah, okay', 'right', 'Good. Good.', 'Uhum.', 'Nice.', 'Whom', '네.', '好啦。', 'Skenkálne', 'Get article'].entries()) {
      await emit({ type: 'input_audio_buffer.speech_started', item_id: 'filler' + index });
      await emit({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'filler' + index, transcript });
    }
    assert.equal(overlay.getOverlayState().streamingAnswer, closureAnswer);
    assert.equal(await window.webContents.executeJavaScript(`window.__voiceMessages.slice(${beforeFillers}).some(message => message.type === 'response.create' || message.type === 'response.cancel')`), false);
    await emit({ type: 'response.done', response: { id: 'reply1', status: 'completed' } });
    await wait(100);
    assert.equal(overlay.getOverlayState().generationMode, 'openai');
    assert.equal((await require('../dist/main/services/sessionService').listSessions()).length, 1);
    const historyStore = require('../dist/main/services/sessionService');
    const firstSaved = (await historyStore.listSessions())[0];
    assert.ok(firstSaved.practiceSessionId, 'Saved turns must carry a conversation scope');
    await historyStore.saveSession({ question: 'Question from an older conversation', answer: 'Old answer', snippets: [], practiceSessionId: 'older-conversation' });
    await overlayWindow.webContents.executeJavaScript("const pane = document.querySelector('.overlay-content'); pane.dispatchEvent(new WheelEvent('wheel', {bubbles: true, deltaY: 100})); pane.scrollTop = 100; pane.dispatchEvent(new Event('scroll', {bubbles: true}))");
    await wait(100);
    assert.equal(overlay.getOverlayState().assistTurn.held, true, 'Scrolling down must protect the reading position');
    const readingPosition = await overlayWindow.webContents.executeJavaScript("document.querySelector('.overlay-content').scrollTop");
    await emit({ type: 'input_audio_buffer.speech_started', item_id: 'turn2' });
    await wait(3100);
    await emit({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'turn2', transcript: 'What is two plus two?' });
    const secondQuestion = 'What is a closure? What is two plus two?';
    assert.ok(await window.webContents.executeJavaScript(`window.__voiceMessages.some(m => m.type === 'conversation.item.create' && m.item.content[0].text?.includes(${JSON.stringify(secondQuestion)}))`), 'Speech starting within three seconds must combine even if its transcript arrives later');
    await emit({ type: 'response.created', response: { id: 'reply2' } });
    await emit({ type: 'response.done', response: { id: 'reply2', status: 'completed', output: [{ content: [{ text: 'Four.' }] }] } });
    await wait(100);
    const scopedHistory = (await historyStore.listSessions()).filter(item => item.practiceSessionId === firstSaved.practiceSessionId);
    assert.equal(scopedHistory.length, 2, 'Every completed question/answer must be saved');
    assert.equal(overlay.getOverlayState().answerQuestion, 'What is a closure?', 'Reading hold must retain the displayed answer');
    assert.equal(overlay.getOverlayState().pendingVoiceAnswer, true);
    assert.equal(await overlayWindow.webContents.executeJavaScript("document.querySelector('.overlay-content').scrollTop"), readingPosition, 'A pending answer must not move the reading position');
    await overlayWindow.webContents.executeJavaScript("document.querySelector('[aria-label=\"Show new answer\"]').click()");
    await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, secondQuestion);
    assert.equal(await overlayWindow.webContents.executeJavaScript("document.querySelector('[aria-label=\"Previous voice answer\"]')?.textContent.includes('lexical scope')"), true);
    const navigateOverlay = direction => overlayWindow.webContents.executeJavaScript(`document.querySelector('[aria-label="${direction} question"]').click()`);
    await navigateOverlay('Previous'); await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, 'What is a closure?');
    await navigateOverlay('Previous'); await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, 'What is a closure?', 'Previous must stop at the current conversation boundary');
    await navigateOverlay('Next'); await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, secondQuestion);
    await click('Mute input');
    assert.equal(await window.webContents.executeJavaScript('window.__voiceTracks[0].enabled'), false);
    await click('Unmute input');
    await window.webContents.executeJavaScript(`const select = document.querySelector('[aria-label="Voice screenshot source"]'); const setter = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; setter.call(select, 'window:test'); select.dispatchEvent(new Event('change', { bubbles: true }));`);
    await click('Send screenshot as context'); await wait(100);
    const image = await window.webContents.executeJavaScript("window.__voiceMessages.find(message => message.type === 'conversation.item.create' && message.item.content[0].type === 'input_image')");
    assert.equal(image.item.content[0].type, 'input_image');
    assert.match(image.item.content[0].image_url, /^data:image\/jpeg;base64,/);
    await emit({ type: 'conversation.item.added', item: { id: image.item.id } });
    assert.equal(await window.webContents.executeJavaScript("window.__voiceMessages.filter(message => message.type === 'response.create').length"), 3);
    assert.equal(await window.webContents.executeJavaScript("document.querySelector('[aria-label=\"Continuous API voice\"]').textContent.includes('Screenshot received')"), true);
    await fs.mkdir(path.resolve(__dirname, '../capture-tests'), { recursive: true });
    await fs.writeFile(path.resolve(__dirname, '../capture-tests/realtime-voice.png'), (await window.webContents.capturePage()).toPNG());
    await assert.rejects(service.publishRealtimeVoice(window.webContents.id + 1, 'wrong', {}), /matching/);
    await overlayWindow.webContents.executeJavaScript("document.querySelector('[aria-label=\"Stop continuous API voice\"]').click()"); await wait(100);
    assert.equal(service.isRealtimeVoiceActive(), false);
    assert.equal(await window.webContents.executeJavaScript('window.__voiceTracks.every(track => track.stopped)'), true);
    await navigateOverlay('Previous'); await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, 'What is a closure?', 'Stopping must retain this conversation for review');
    global.fetch = async () => new Response('v=0\r\n', { status: 200 });
    await service.connectRealtimeVoice(window.webContents.id, 'v=0\r\n');
    assert.notEqual(require('../dist/main/services/practiceSessionService').getPracticeSessionId(), firstSaved.practiceSessionId);
    await navigateOverlay('Previous'); await wait(100);
    assert.equal(overlay.getOverlayState().answerQuestion, '', 'A new conversation must not navigate to prior conversations');
    assert.equal((await historyStore.listSessions()).length, 3, 'Prior archives must remain safely stored');
    service.stopRealtimeVoice();
    assert.equal(await window.webContents.executeJavaScript("JSON.stringify(window.interviewAPI).includes('test-key-never-exposed')"), false);
    global.fetch = async () => new Response('', { status: 429 });
    await assert.rejects(service.connectRealtimeVoice(window.webContents.id, 'v=0\r\n'), /quota/);
    assert.equal(service.isRealtimeVoiceActive(), false);
    console.log('PASS: current-conversation overlay navigation, new-session boundary, complete turn persistence, late transcripts, interruption ordering, missing key, quota failure, typed IPC ownership, voice-panel start/stop/mute, image message/acknowledgement, and track cleanup. WebRTC and API are mocked; live audio/model behavior is NOT tested.');
  } catch (error) { console.error(error); exitCode = 1; }
  finally { service?.stopRealtimeVoice(); require('../dist/main/services/overlayService').destroyOverlayWindow(); global.fetch = originalFetch; await fs.rm(directory, { recursive: true, force: true }); window?.destroy(); app.exit(exitCode); }
});
